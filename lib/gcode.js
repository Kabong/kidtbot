/* Gcode generation for the MidTBot plotter.
   Pure functions, no I/O — so the simulator and the test suite can use them
   without touching the network or the hardware. */

/** Ramer–Douglas–Peucker: drop points that don't change the shape.
    `eps` is in the same units as the points (normalized 0–1 here). */
function simplify(pts, eps) {
  if (pts.length <= 2 || eps <= 0) return pts;

  // Perpendicular distance from p to the line a→b.
  const dist = (p, a, b) => {
    const dx = b.x - a.x, dy = b.y - a.y;
    const len2 = dx * dx + dy * dy;
    if (len2 === 0) return Math.hypot(p.x - a.x, p.y - a.y);
    let t = ((p.x - a.x) * dx + (p.y - a.y) * dy) / len2;
    t = Math.max(0, Math.min(1, t));
    return Math.hypot(p.x - (a.x + t * dx), p.y - (a.y + t * dy));
  };

  // Iterative (not recursive) so a 5000-point kid scribble can't blow the stack.
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];

  while (stack.length) {
    const [lo, hi] = stack.pop();
    let far = -1, maxD = eps;
    for (let i = lo + 1; i < hi; i++) {
      const d = dist(pts[i], pts[lo], pts[hi]);
      if (d > maxD) { maxD = d; far = i; }
    }
    if (far !== -1) {
      keep[far] = 1;
      stack.push([lo, far], [far, hi]);
    }
  }
  return pts.filter((_, i) => keep[i]);
}

/** Bounding box over every point in every stroke. */
function bounds(strokes) {
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  for (const stroke of strokes) {
    for (const pt of stroke) {
      if (pt.x < minX) minX = pt.x;
      if (pt.x > maxX) maxX = pt.x;
      if (pt.y < minY) minY = pt.y;
      if (pt.y > maxY) maxY = pt.y;
    }
  }
  return { minX, maxX, minY, maxY };
}

/**
 * Turn normalized strokes (0–1, canvas orientation: Y=0 at top) into gcode.
 * Returns { lines, meta } — meta carries everything the simulator wants to
 * show and everything the UI wants to report.
 */
function strokesToGcode(strokes, config) {
  const {
    plotWidth, plotHeight, penDownCmd, penUpCmd, drawSpeed, moveSpeed,
    penLiftDelay, penLiftZ, simplifyEps = 0,
  } = config;

  // Drop degenerate strokes first, then simplify what's left.
  let work = strokes.filter(s => s && s.length >= 2);
  const pointsBefore = work.reduce((a, s) => a + s.length, 0);
  if (simplifyEps > 0) work = work.map(s => simplify(s, simplifyEps));
  const pointsAfter = work.reduce((a, s) => a + s.length, 0);

  if (work.length === 0) {
    return { lines: [], meta: { empty: true, pointsBefore, pointsAfter } };
  }

  const { minX, maxX, minY, maxY } = bounds(work);
  const spanX = (maxX - minX) || 0.001;
  const spanY = (maxY - minY) || 0.001;

  // Fit inside the plot area, preserving aspect ratio, with a 5% margin.
  const margin = Math.min(plotWidth, plotHeight) * 0.05;
  const availW = plotWidth - 2 * margin;
  const availH = plotHeight - 2 * margin;
  const scale = Math.min(availW / spanX, availH / spanY);

  const originX = margin + (availW - spanX * scale) / 2;
  const originY = margin + (availH - spanY * scale) / 2;

  // Canvas Y grows downward, plotter Y grows away from the user — flip it.
  const px = nx => (originX + (nx - minX) * scale);
  const py = ny => (originY + (maxY - ny) * scale);
  const fx = nx => px(nx).toFixed(3);
  const fy = ny => py(ny).toFixed(3);

  const useZ = penLiftZ > 0;
  const dwell = `G4 P${(penLiftDelay / 1000).toFixed(2)}`;  // G4 P is seconds
  const penUpSeq   = useZ ? [penUpCmd, `G0 Z${penLiftZ.toFixed(2)}`, dwell] : [penUpCmd, dwell];
  const penDownSeq = useZ ? [penDownCmd, `G0 Z0`, dwell]                    : [penDownCmd, dwell];

  const lines = [
    '; MidTBot drawing - generated by Kids UI',
    `; plot area ${plotWidth}x${plotHeight}mm, scale ${scale.toFixed(2)}, ` +
      `${work.length} strokes, ${pointsAfter} points`,
    'G21',  // millimeters
    'G90',  // absolute positioning
  ];

  // Lift before any motion, THEN zero XY. G92 must not touch Z, or the
  // pen-up height stops meaning anything physical.
  let penIsUp = false;
  const liftPen = () => { if (!penIsUp) { lines.push(...penUpSeq); penIsUp = true; } };
  const dropPen = () => { if (penIsUp) { lines.push(...penDownSeq); penIsUp = false; } };

  liftPen();
  lines.push('G92 X0 Y0');
  lines.push(`G0 F${moveSpeed}`);

  for (const stroke of work) {
    liftPen();
    lines.push(`G0 X${fx(stroke[0].x)} Y${fy(stroke[0].y)}`);  // travel
    dropPen();
    // Start at 1: we're already standing on point 0 after the G0 above.
    for (let i = 1; i < stroke.length; i++) {
      lines.push(`G1 F${drawSpeed} X${fx(stroke[i].x)} Y${fy(stroke[i].y)}`);
    }
  }

  liftPen();           // no-op if the last stroke already lifted
  lines.push('G0 X0 Y0');

  const actionable = lines.filter(l => l.trim() && !l.startsWith(';')).length;

  return {
    lines,
    meta: {
      empty: false,
      strokeCount: work.length,
      pointsBefore,
      pointsAfter,
      actionable,
      scale,
      useZ,
      drawnBox: {
        x: px(minX), y: py(maxY),
        w: spanX * scale, h: spanY * scale,
      },
      plotWidth, plotHeight, margin,
    },
  };
}

module.exports = { strokesToGcode, simplify, bounds };
