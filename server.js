const express = require('express');
const axios = require('axios');
const fs = require('fs');
const path = require('path');

const app = express();
app.use(express.json({ limit: '2mb' }));
app.use(express.static(path.join(__dirname, 'public')));

// --- Config ---
const CONFIG_PATH = path.join(__dirname, 'config.json');
let config = JSON.parse(fs.readFileSync(CONFIG_PATH, 'utf8'));

function saveConfig() {
  fs.writeFileSync(CONFIG_PATH, JSON.stringify(config, null, 2));
}

// --- Job tracking ---
const jobs = new Map();

// --- Gcode generation ---
function strokesToGcode(strokes) {
  const { plotWidth, plotHeight, penDownCmd, penUpCmd, drawSpeed, moveSpeed, penLiftDelay, penLiftZ } = config;

  // Find bounding box of all strokes
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  for (const stroke of strokes) {
    for (const pt of stroke) {
      if (pt.x < minX) minX = pt.x;
      if (pt.x > maxX) maxX = pt.x;
      if (pt.y < minY) minY = pt.y;
      if (pt.y > maxY) maxY = pt.y;
    }
  }

  const spanX = maxX - minX || 0.001;
  const spanY = maxY - minY || 0.001;

  // Scale to fit plot area with 5% margin
  const margin = Math.min(plotWidth, plotHeight) * 0.05;
  const availW = plotWidth - 2 * margin;
  const availH = plotHeight - 2 * margin;
  const scale = Math.min(availW / spanX, availH / spanY);

  // Center drawing in plot area
  const startX = margin + (availW - spanX * scale) / 2;
  const startY = margin + (availH - spanY * scale) / 2;

  // Convert normalized coords to plotter coords
  // Canvas Y=0 is top, plotter Y=0 is front (near user) — flip Y axis
  const px = (nx) => (startX + (nx - minX) * scale).toFixed(3);
  const py = (ny) => (startY + (maxY - ny) * scale).toFixed(3);

  const dwell = `G4 P${(penLiftDelay / 1000).toFixed(2)}`;  // G4 takes seconds

  // Build pen up / pen down sequences
  // penLiftZ > 0: Z=0 is pen-down (touching paper), Z=penLiftZ is pen-up (lifted)
  // G92 only resets XY — never Z — so Z coordinates stay physically meaningful
  const penUp = penLiftZ > 0
    ? [penUpCmd, `G0 Z${penLiftZ.toFixed(2)}`, dwell]
    : [penUpCmd, dwell];
  const penDown = penLiftZ > 0
    ? [penDownCmd, `G0 Z0`, dwell]
    : [penDownCmd, dwell];

  const lines = [
    '; MidTBot drawing - generated by Kids UI',
    'G21',  // millimeters
    'G90',  // absolute positioning
    // Lift pen first, before any movement
    ...penUp,
    'G92 X0 Y0',  // set XY origin at current position — Z intentionally excluded
    `G0 F${moveSpeed}`,
  ];

  for (const stroke of strokes) {
    if (stroke.length < 2) continue;
    const first = stroke[0];
    lines.push(`G0 X${px(first.x)} Y${py(first.y)}`);  // travel with pen up
    lines.push(...penDown);
    for (const pt of stroke) {
      lines.push(`G1 F${drawSpeed} X${px(pt.x)} Y${py(pt.y)}`);
    }
    lines.push(...penUp);
  }

  // Return home with pen guaranteed up
  lines.push(...penUp);
  lines.push(`G0 X0 Y0`);
  return lines;
}

// --- Send gcode to ESP32 ---
async function sendGcodeLines(lines, jobId) {
  const job = jobs.get(jobId);
  const actionableLines = lines.filter(l => l.trim() && !l.startsWith(';'));
  job.total = actionableLines.length;
  job.progress = 0;

  for (let i = 0; i < actionableLines.length; i++) {
    if (job.cancelled) {
      job.status = 'cancelled';
      return;
    }

    const line = actionableLines[i];
    let sent = false;
    for (let attempt = 1; attempt <= 3; attempt++) {
      try {
        await axios.get(`http://${config.esp32Ip}/command`, {
          params: { commandText: line },
          timeout: 8000
        });
        sent = true;
        break;
      } catch (err) {
        if (attempt === 3) {
          throw new Error(`Failed after 3 attempts at line ${i + 1} ("${line}"): ${err.message}`);
        }
        await new Promise(r => setTimeout(r, 300)); // brief pause before retry
      }
    }

    job.progress = i + 1;
    await new Promise(r => setTimeout(r, config.cmdDelayMs));
  }
}

async function runPlotJob(jobId, strokes) {
  const job = jobs.get(jobId);
  try {
    const lines = strokesToGcode(strokes);
    job.gcodeLines = lines.length;
    // Log gcode to console for debugging
    console.log('\n--- GCODE PREVIEW (first 30 lines) ---');
    lines.slice(0, 30).forEach(l => console.log(l));
    if (lines.length > 30) console.log(`... (${lines.length - 30} more lines)`);
    console.log('--- END PREVIEW ---\n');
    await sendGcodeLines(lines, jobId);
    if (job.status !== 'cancelled') {
      job.status = 'done';
    }
  } catch (err) {
    job.status = 'error';
    job.error = err.message;
  }
}

// --- Routes ---

app.get('/api/status', async (req, res) => {
  try {
    await axios.get(`http://${config.esp32Ip}/command`, {
      params: { commandText: '?' },
      timeout: 3000
    });
    res.json({ connected: true, ip: config.esp32Ip });
  } catch {
    res.json({ connected: false, ip: config.esp32Ip });
  }
});

app.post('/api/plot', (req, res) => {
  const { strokes } = req.body;
  if (!strokes || !Array.isArray(strokes) || strokes.length === 0) {
    return res.status(400).json({ error: 'No strokes provided' });
  }

  const jobId = Date.now().toString();
  jobs.set(jobId, { status: 'running', progress: 0, total: 0, error: null, cancelled: false });
  runPlotJob(jobId, strokes);
  res.json({ jobId });
});

app.get('/api/plot/:jobId', (req, res) => {
  res.setHeader('Content-Type', 'text/event-stream');
  res.setHeader('Cache-Control', 'no-cache');
  res.setHeader('Connection', 'keep-alive');

  const { jobId } = req.params;

  const send = () => {
    const job = jobs.get(jobId);
    if (!job) {
      res.write(`data: ${JSON.stringify({ status: 'not-found' })}\n\n`);
      clearInterval(timer);
      res.end();
      return;
    }
    res.write(`data: ${JSON.stringify(job)}\n\n`);
    if (job.status === 'done' || job.status === 'error' || job.status === 'cancelled') {
      clearInterval(timer);
      setTimeout(() => { jobs.delete(jobId); }, 5000);
      res.end();
    }
  };

  send(); // send immediately
  const timer = setInterval(send, 400);
  req.on('close', () => clearInterval(timer));
});

app.post('/api/stop', (req, res) => {
  // Cancel any running job
  for (const [, job] of jobs) {
    if (job.status === 'running') {
      job.cancelled = true;
    }
  }
  // Also send M5 (pen up) to the ESP32 as a safety measure
  axios.get(`http://${config.esp32Ip}/command`, {
    params: { commandText: config.penUpCmd },
    timeout: 3000
  }).catch(() => {});
  res.json({ ok: true });
});

app.get('/api/config', (req, res) => {
  res.json(config);
});

app.post('/api/config', (req, res) => {
  const allowed = ['esp32Ip', 'plotWidth', 'plotHeight', 'penDownCmd', 'penUpCmd', 'drawSpeed', 'moveSpeed', 'cmdDelayMs', 'penLiftDelay', 'penLiftZ'];
  for (const key of allowed) {
    if (req.body[key] !== undefined) config[key] = req.body[key];
  }
  saveConfig();
  res.json({ ok: true });
});

// --- Start ---
const PORT = 3000;
app.listen(PORT, () => {
  console.log(`\n🎨 MidTBot Kids UI is running!`);
  console.log(`   Open: http://localhost:${PORT}`);
  console.log(`   (or from another device on your network: http://<your-pc-ip>:${PORT})\n`);
});
